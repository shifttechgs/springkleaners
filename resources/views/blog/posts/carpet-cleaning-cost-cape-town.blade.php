<p class="text-muted text-[15.5px] leading-[1.85] mb-5">
    As a general rule: once a year for a typical household, every 6 months if you've got kids or pets, and every 3 months if anyone at home deals with allergies or asthma. Wall-to-wall carpet in the Northern Suburbs has one extra factor working against it — sea-air humidity and sand tracked in underfoot in coastal areas like Bloubergstrand, Big Bay and Table View, which speeds up musty odour build-up compared to homes further inland. If you're close to the coast, lean toward the more frequent end of that range.
